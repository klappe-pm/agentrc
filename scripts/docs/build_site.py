class Site:
    def __init__(self, repo: Path, out: Path, capture_root: Path | None = None):
        self.repo = repo
        self.out = out
        self.capture_root = capture_root or repo
        self.pages: dict[str, dict] = {}  # source path -> {out, title, html, ids, section}
        self.errors: list[str] = []

    # source discovery

    def out_path(self, source: str) -> str:
        if source == SITE_SOURCE + "/index.md":
            return "index.html"
        path = Path(source)
        if path.name == "README.md":
            return str(path.parent / "index.html")
        return str(path.with_suffix(".html"))

    def discover(self) -> list[str]:
        found = []
        for section, _ in SECTIONS:
            base = self.repo / section
            if not base.is_dir():
                continue
            for path in sorted(base.rglob("*.md")):
                rel = path.relative_to(self.repo).as_posix()
                if rel.startswith(SITE_SOURCE + "/") and rel != SITE_SOURCE + "/index.md":
                    continue
                found.append(rel)
        return found

    # link resolution

    def resolve(self, source: str, target: str) -> str:
        if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I):
            return target
        path, _, fragment = target.partition("#")
        suffix = f"#{fragment}" if fragment else ""
        if not path:
            return suffix or "#"
        joined = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
        here = self.out_path(source)
        if joined == "load.html":
            return posixpath.relpath("load.html", posixpath.dirname(here) or ".") + suffix
        candidates = [joined, posixpath.join(joined, "README.md")]
        for candidate in candidates:
            if candidate in self.known:
                return posixpath.relpath(self.out_path(candidate), posixpath.dirname(here) or ".") + suffix
        if joined.startswith(".."):
            self.errors.append(f"{source}: link {target} leaves the repository")
            return target
        full = self.repo / joined
        if full.is_dir():
            return f"{REPO_URL}/tree/main/{joined}"
        if full.exists():
            return f"{REPO_URL}/blob/main/{joined}"
        self.errors.append(f"{source}: link {target} does not resolve")
        return target

    # capture

    def capture(self) -> str:
        env = dict(os.environ)
        env["PYTHONPATH"] = str(ENGINE_ROOT)
        env["PYTHONDONTWRITEBYTECODE"] = "1"
        env["NO_COLOR"] = "1"
        with tempfile.TemporaryDirectory() as home:
            env["STRATARC_HOME"] = home
            result = subprocess.run([sys.executable, "-m", "stratarc", *CAPTURE_ARGS], cwd=self.capture_root, env=env, capture_output=True, text=True)
        if result.returncode != 0:
            raise BuildError(f"the captured example failed with exit {result.returncode}: {result.stderr.strip()}")
        text = result.stdout.rstrip("\n")
        if any(marker in text for marker in ("/" + "Users" + "/", "/home/", str(self.capture_root))):
            raise BuildError("the captured example contains a machine path")
        return f"```text\n$ {CAPTURE_SHOWN}\n{text}\n```"

    # build

    def build(self) -> None:
        sources = self.discover()
        self.known = set(sources)
        if SITE_SOURCE + "/index.md" not in self.known:
            raise BuildError(f"{SITE_SOURCE}/index.md is missing")
        for source in sources:
            text = (self.repo / source).read_text(encoding="utf-8")
            if "{{capture:config-explain}}" in text:
                text = text.replace("{{capture:config-explain}}", self.capture())
            renderer = Renderer(source, self.resolve)
            body = renderer.render(text)
            self.pages[source] = {"out": self.out_path(source), "title": renderer.title or Path(source).stem, "html": body, "ids": renderer.ids}
        if self.errors:
            raise BuildError("broken links:\n  " + "\n  ".join(sorted(set(self.errors))))

        if self.out.exists():
            shutil.rmtree(self.out)
        self.out.mkdir(parents=True)
        shutil.copyfile(TEMPLATES / "site.css", self.out / "site.css")
        shutil.copyfile(TEMPLATES / "load.html", self.out / "load.html")
        template = string.Template((TEMPLATES / "page.html").read_text(encoding="utf-8"))
        for source, page in self.pages.items():
            target = self.out / page["out"]
            target.parent.mkdir(parents=True, exist_ok=True)
            depth = len(Path(page["out"]).parts) - 1
            root = "/".join([".."] * depth) if depth else "."
            title = page["title"] if page["out"] == "index.html" else f"{page['title']} | stratarc"
            target.write_text(
                template.substitute(title=html.escape(title), root=root, nav=self.nav(page["out"]), body=page["html"]),
                encoding="utf-8",
            )

    def nav(self, current: str) -> str:
        def link(source: str, label: str) -> str:
            page = self.pages[source]
            href = posixpath.relpath(page["out"], posixpath.dirname(current) or ".")
            mark = ' aria-current="page"' if page["out"] == current else ""
            return f'<li><a href="{html.escape(href)}"{mark}>{html.escape(label)}</a></li>'

        home = posixpath.relpath("index.html", posixpath.dirname(current) or ".")
        first = posixpath.relpath("load.html", posixpath.dirname(current) or ".")
        parts = [f'<ul><li><a href="{home}"' + (' aria-current="page"' if current == "index.html" else "") + f'>home</a></li><li><a href="{first}">first run</a></li></ul>']
        for section, heading in SECTIONS:
            members = [s for s in self.pages if s.startswith(section + "/") and not s.startswith(SITE_SOURCE + "/")]
            if not members:
                continue

            def rank(source: str) -> tuple:
                rest = Path(source).relative_to(section)
                group = rest.parts[0] if len(rest.parts) > 1 else ""
                order = QUADRANTS.index(group) if group in QUADRANTS else (-1 if not group else len(QUADRANTS))
                return (order, group, rest.name != "README.md", str(rest))

            members.sort(key=rank)
            parts.append(f"<h2>{html.escape(heading)}</h2>")
            items = []
            for source in members:
                rest = Path(source).relative_to(section)
                if rest.name == "README.md":
                    label = "overview" if len(rest.parts) == 1 else "/".join(rest.parts[:-1])
                else:
                    label = self.pages[source]["title"]
                    if len(rest.parts) > 2:
                        label = "/".join(rest.parts[1:-1]) + ": " + label
                items.append(link(source, label))
            parts.append("<ul>" + "".join(items) + "</ul>")
        return "\n".join(parts)


def build_site(repo: Path, out: Path) -> Site:
    site = Site(repo, out)
    site.build()
    return site


# ----- command line -----


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="build_site.py", description="Build the documentation site, or check its generated pages.")
    parser.add_argument("--repo", metavar="PATH", default=str(ENGINE_ROOT), help="the repository whose docs/ and developer-docs/ are read (default: this repository)")
    parser.add_argument("--out", metavar="DIR", help="where to build the site (default: site/ under the repository)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 6 when a committed generated page differs from the code; build nothing")
    mode.add_argument("--write-generated", action="store_true", help="rewrite the committed generated pages from the code; build nothing")
    try:
        args = parser.parse_args(argv)
    except SystemExit as stop:
        return 0 if stop.code in (0, None) else 2
    repo = Path(args.repo).resolve()
    if not repo.is_dir():
        print(f"error: {repo} is not a directory", file=sys.stderr)
        return 2
    sys.path.insert(0, str(ENGINE_ROOT))
    try:
        if args.check:
            stale = check_generated(repo)
            for rel in stale:
                print(f"stale: {rel}", file=sys.stderr)
            if stale:
                print("run: python3 scripts/docs/build_site.py --write-generated", file=sys.stderr)
                return 6
            print("generated pages match the code")
            return 0
        if args.write_generated:
            for rel in write_generated(repo):
                print(f"wrote {rel}")
            return 0
        out = Path(args.out).resolve() if args.out else repo / "site"
        site = build_site(repo, out)
    except BuildError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    print(f"built {len(site.pages)} pages into {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
