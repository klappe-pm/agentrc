#!/usr/bin/env python3
"""Build the static documentation site, and keep its generated pages from drifting.

The site is built from the Markdown under docs/ and developer-docs/ with the standard library only: a left navigation, no search, no JavaScript, light and dark by the reader's system setting. The landing page and the first-run load page come from docs/site-source/ and scripts/docs/templates/.

Two pages are generated from the code so they cannot drift from it: the command reference from the argparse tree of `stratarc.cli`, and the error catalog from `stratarc.messages`. They are committed under docs/reference/generated/.

    build_site.py                    build the site into site/
    build_site.py --out DIR          build into DIR
    build_site.py --write-generated  rewrite the committed generated pages
    build_site.py --check            exit 6 when a committed generated page differs

This is a development tool. It is not part of the installed package.

Exit statuses: 0 ok, 1 build failure (a broken link, a failed capture), 2 invalid input, 6 a committed generated page differs from the code.
"""

