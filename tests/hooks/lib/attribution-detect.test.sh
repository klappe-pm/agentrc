#!/usr/bin/env bash
# Behavioral tests for hooks/lib/attribution-detect.py
#
# The shared detector must recognize every attribution form the runtime emits,
# leave ordinary prose alone, strip attribution lines out of a commit message
# without eating the subject or body, and judge a PreToolUse payload on the
# right fields for the tool. Agent names are assembled from fragments so this
# file carries no literal attribution line for the live guard to block on.

