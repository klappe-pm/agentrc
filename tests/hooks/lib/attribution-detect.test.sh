# assert_payload <label> <json> <dirty|clean>
assert_payload() {
  local label="$1" json="$2" expect="$3" out got
  out=$(printf '%s' "$json" | python3 "$DETECT" detect-payload || true)
  [ -n "$out" ] && got=dirty || got=clean
  [ "$got" = "$expect" ] && record yes "$label" "$expect" "$got" || record no "$label" "$expect" "$got"
}

