PASS=0
FAIL=0

record() {
  local ok="$1" label="$2" expect="$3" got="$4"
  if [ "$ok" = "yes" ]; then
    PASS=$((PASS+1))
  else
    FAIL=$((FAIL+1))
    printf '  attribution-detect.py FAIL  %-42s expected=%-14s got=%s\n' "$label" "$expect" "$got" >&2
  fi
}

# assert_detect <label> <text> <dirty|clean>
assert_detect() {
  local label="$1" text="$2" expect="$3" out got
  out=$(printf '%s' "$text" | python3 "$DETECT" detect || true)
  [ -n "$out" ] && got=dirty || got=clean
  [ "$got" = "$expect" ] && record yes "$label" "$expect" "$got" || record no "$label" "$expect" "$got"
}

